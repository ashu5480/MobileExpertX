import type { Product, ProductImage, ProductSpec } from '@/types';

/**
 * Seed catalogue.
 *
 * `images[].url` is intentionally empty: the UI renders a high-fidelity
 * generated `ProductVisual` (CSS 3D + SVG) so the site looks complete without
 * shipping binary assets. Drop real photography URLs in here (or point the CMS
 * at an object store) and the gallery switches to `next/image` automatically.
 *
 * All prices are stored in **paise** (₹1 = 100 paise).
 */

const img = (alt: string, view: ProductImage['view'] = 'front'): ProductImage => ({
  url: '',
  alt,
  view,
});

const GROUPS = [
  'display',
  'performance',
  'camera',
  'battery',
  'network',
  'body',
  'software',
] as const;

/** Builds the 7 standard spec rows from a compact tuple. */
const S = (
  display: string,
  performance: string,
  camera: string,
  battery: string,
  network: string,
  body: string,
  software: string,
): ProductSpec[] => {
  const values = [display, performance, camera, battery, network, body, software];
  return GROUPS.map((group, i) => ({
    group,
    label: group[0].toUpperCase() + group.slice(1),
    value: values[i],
  }));
};

type P = Omit<Product, 'images' | 'specs' | 'highlights' | 'colors' | 'storages' | 'rams' | 'tags'> &
  Partial<Product>;

